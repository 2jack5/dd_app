-- 售后工单与工单事件
-- 按文件编号升序执行；本文件与对应 down 文件由迁移工具记录版本。
BEGIN;

CREATE TABLE after_sales_cases (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  case_no varchar(40) NOT NULL,
  kind varchar(24) NOT NULL,
  reporter_id bigint NOT NULL,
  order_id bigint,
  target_user_id bigint,
  review_id bigint,
  category_code varchar(48) NOT NULL,
  content text NOT NULL,
  evidence_asset_ids jsonb NOT NULL DEFAULT '[]'::jsonb,
  status varchar(24) NOT NULL,
  assignee_id bigint,
  blocks_settlement boolean NOT NULL DEFAULT false,
  resolution_code varchar(48),
  resolution_note text,
  resolved_at timestamptz,
  version integer NOT NULL DEFAULT 1
);

COMMENT ON TABLE after_sales_cases IS '投诉、客服与申诉工单';

COMMENT ON COLUMN after_sales_cases.case_no IS '工单编号';

COMMENT ON COLUMN after_sales_cases.kind IS 'COMPLAINT/SUPPORT/REVIEW_APPEAL';

COMMENT ON COLUMN after_sales_cases.reporter_id IS '→users';

COMMENT ON COLUMN after_sales_cases.order_id IS '→orders；普通帮助可空';

COMMENT ON COLUMN after_sales_cases.target_user_id IS '→users';

COMMENT ON COLUMN after_sales_cases.review_id IS '→reviews';

COMMENT ON COLUMN after_sales_cases.category_code IS '投诉或问题分类';

COMMENT ON COLUMN after_sales_cases.content IS '问题描述';

COMMENT ON COLUMN after_sales_cases.evidence_asset_ids IS '默认 []';

COMMENT ON COLUMN after_sales_cases.status IS 'OPEN/ASSIGNED/INVESTIGATING/WAIT_USER/RESOLVED/CLOSED';

COMMENT ON COLUMN after_sales_cases.assignee_id IS '→admin_users';

COMMENT ON COLUMN after_sales_cases.blocks_settlement IS '默认 false；是否冻结该订单结算';

COMMENT ON COLUMN after_sales_cases.resolution_code IS '处理结论';

COMMENT ON COLUMN after_sales_cases.resolution_note IS '对用户可见结论';

COMMENT ON COLUMN after_sales_cases.resolved_at IS '结案时间';

COMMENT ON COLUMN after_sales_cases.version IS '默认 1；更新时通过 WHERE version 校验并显式递增';

CREATE TABLE case_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  case_id bigint NOT NULL,
  actor_type varchar(16) NOT NULL,
  actor_id bigint,
  event_type varchar(32) NOT NULL,
  visibility varchar(16) NOT NULL,
  content text NOT NULL,
  evidence_asset_ids jsonb NOT NULL DEFAULT '[]'::jsonb,
  event_key varchar(160) NOT NULL
);

COMMENT ON TABLE case_events IS '工单流转与补充证据';

COMMENT ON COLUMN case_events.case_id IS '→after_sales_cases';

COMMENT ON COLUMN case_events.actor_type IS 'USER/ADMIN/SYSTEM';

COMMENT ON COLUMN case_events.actor_id IS '操作者';

COMMENT ON COLUMN case_events.event_type IS 'COMMENT/ASSIGN/REQUEST_EVIDENCE/RESOLVE/REOPEN';

COMMENT ON COLUMN case_events.visibility IS 'PUBLIC/INTERNAL';

COMMENT ON COLUMN case_events.content IS '补充说明';

COMMENT ON COLUMN case_events.evidence_asset_ids IS '默认 []';

COMMENT ON COLUMN case_events.event_key IS '唯一事件键';

CREATE UNIQUE INDEX uq_after_sales_cases_case_no ON after_sales_cases (case_no);

CREATE UNIQUE INDEX uq_case_events_event_key ON case_events (event_key);

CREATE INDEX ix_after_sales_cases_1 ON after_sales_cases (reporter_id);

CREATE INDEX ix_after_sales_cases_2 ON after_sales_cases (order_id);

CREATE INDEX ix_after_sales_cases_3 ON after_sales_cases (target_user_id);

CREATE INDEX ix_after_sales_cases_4 ON after_sales_cases (review_id);

CREATE INDEX ix_after_sales_cases_5 ON after_sales_cases (assignee_id);

CREATE INDEX ix_case_events_1 ON case_events (case_id);

ALTER TABLE after_sales_cases ADD CONSTRAINT ck_after_sales_cases_kind CHECK (kind IN ('COMPLAINT','SUPPORT','REVIEW_APPEAL'));

ALTER TABLE after_sales_cases ADD CONSTRAINT ck_after_sales_cases_status CHECK (status IN ('OPEN','ASSIGNED','INVESTIGATING','WAIT_USER','RESOLVED','CLOSED'));

ALTER TABLE after_sales_cases ADD CONSTRAINT ck_after_sales_cases_version_positive CHECK (version>0);

ALTER TABLE case_events ADD CONSTRAINT ck_case_events_actor_type CHECK (actor_type IN ('USER','ADMIN','SYSTEM'));

ALTER TABLE case_events ADD CONSTRAINT ck_case_events_event_type CHECK (event_type IN ('COMMENT','ASSIGN','REQUEST_EVIDENCE','RESOLVE','REOPEN'));

ALTER TABLE case_events ADD CONSTRAINT ck_case_events_visibility CHECK (visibility IN ('PUBLIC','INTERNAL'));

ALTER TABLE after_sales_cases ADD CONSTRAINT ck_case_blocking_order CHECK (NOT blocks_settlement OR order_id IS NOT NULL);

CREATE INDEX ix_after_sales_cases_6 ON after_sales_cases (reporter_id, created_at DESC);

CREATE INDEX ix_after_sales_cases_7 ON after_sales_cases (status, assignee_id, created_at);

CREATE INDEX ix_after_sales_cases_8 ON after_sales_cases (order_id, status);

CREATE INDEX ix_case_events_2 ON case_events (case_id, created_at, id);

ALTER TABLE after_sales_cases ADD CONSTRAINT ck_json_after_sales_cases_evidence_asset_ids CHECK (jsonb_typeof(evidence_asset_ids)='array');

ALTER TABLE case_events ADD CONSTRAINT ck_json_case_events_evidence_asset_ids CHECK (jsonb_typeof(evidence_asset_ids)='array');

CREATE TRIGGER tr_case_events_append_only BEFORE UPDATE OR DELETE ON case_events FOR EACH ROW EXECUTE FUNCTION dd_reject_event_mutation();

COMMIT;
