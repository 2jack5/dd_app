-- 评价与内容版本
-- 按文件编号升序执行；本文件与对应 down 文件由迁移工具记录版本。
BEGIN;

CREATE TABLE reviews (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  order_id bigint NOT NULL,
  buyer_id bigint NOT NULL,
  coach_id bigint NOT NULL,
  rating smallint NOT NULL,
  visibility varchar(16) NOT NULL,
  published_at timestamptz
);

COMMENT ON TABLE reviews IS '订单评价主记录';

COMMENT ON COLUMN reviews.order_id IS '→orders';

COMMENT ON COLUMN reviews.buyer_id IS '→users';

COMMENT ON COLUMN reviews.coach_id IS '→coaches';

COMMENT ON COLUMN reviews.rating IS '1..5';

COMMENT ON COLUMN reviews.visibility IS 'PENDING/PUBLISHED/HIDDEN';

COMMENT ON COLUMN reviews.published_at IS '首评公开时间';

CREATE TABLE review_contents (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  review_id bigint NOT NULL,
  kind varchar(16) NOT NULL,
  revision integer NOT NULL,
  content text NOT NULL,
  image_asset_ids jsonb NOT NULL DEFAULT '[]'::jsonb,
  audit_status varchar(16) NOT NULL,
  is_current boolean NOT NULL DEFAULT false,
  published_at timestamptz
);

COMMENT ON TABLE review_contents IS '评价内容版本';

COMMENT ON COLUMN review_contents.review_id IS '→reviews';

COMMENT ON COLUMN review_contents.kind IS 'PRIMARY/FOLLOW_UP';

COMMENT ON COLUMN review_contents.revision IS '版本';

COMMENT ON COLUMN review_contents.content IS '评价正文';

COMMENT ON COLUMN review_contents.image_asset_ids IS '默认 []';

COMMENT ON COLUMN review_contents.audit_status IS 'PENDING/APPROVED/REJECTED';

COMMENT ON COLUMN review_contents.is_current IS '默认 false；该类型当前公开版本';

COMMENT ON COLUMN review_contents.published_at IS '公开时间';

CREATE UNIQUE INDEX uq_reviews_order_id ON reviews (order_id);

CREATE UNIQUE INDEX uq_review_contents_review_id_kind_revision ON review_contents (review_id, kind, revision);

CREATE UNIQUE INDEX uq_review_contents_review_id_kind ON review_contents (review_id, kind) WHERE is_current;

CREATE INDEX ix_reviews_2 ON reviews (buyer_id);

CREATE INDEX ix_reviews_3 ON reviews (coach_id);

CREATE INDEX ix_review_contents_1 ON review_contents (review_id);

ALTER TABLE reviews ADD CONSTRAINT ck_reviews_visibility CHECK (visibility IN ('PENDING','PUBLISHED','HIDDEN'));

ALTER TABLE review_contents ADD CONSTRAINT ck_review_contents_kind CHECK (kind IN ('PRIMARY','FOLLOW_UP'));

ALTER TABLE review_contents ADD CONSTRAINT ck_review_contents_revision_positive CHECK (revision>0);

ALTER TABLE review_contents ADD CONSTRAINT ck_review_contents_audit_status CHECK (audit_status IN ('PENDING','APPROVED','REJECTED'));

ALTER TABLE reviews ADD CONSTRAINT ck_review_rating CHECK (rating BETWEEN 1 AND 5);

ALTER TABLE review_contents ADD CONSTRAINT ck_review_current CHECK (NOT is_current OR audit_status='APPROVED');

CREATE INDEX ix_reviews_4 ON reviews (coach_id, visibility, created_at DESC);

ALTER TABLE review_contents ADD CONSTRAINT ck_json_review_contents_image_asset_ids CHECK (jsonb_typeof(image_asset_ids)='array');

COMMIT;
