-- 后台权限、复核与审计
-- 按文件编号升序执行；本文件与对应 down 文件由迁移工具记录版本。
BEGIN;

CREATE TABLE admin_users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  account varchar(64) NOT NULL,
  password_hash varchar(256) NOT NULL,
  display_name varchar(64) NOT NULL,
  status varchar(16) NOT NULL,
  mfa_secret_cipher bytea,
  auth_version integer NOT NULL DEFAULT 1,
  last_login_at timestamptz
);

COMMENT ON TABLE admin_users IS '后台管理员';

COMMENT ON COLUMN admin_users.account IS '统一转小写的登录名';

COMMENT ON COLUMN admin_users.password_hash IS '强密码哈希；不存明文';

COMMENT ON COLUMN admin_users.display_name IS '名称';

COMMENT ON COLUMN admin_users.status IS 'ACTIVE/DISABLED';

COMMENT ON COLUMN admin_users.mfa_secret_cipher IS '二次认证密钥密文';

COMMENT ON COLUMN admin_users.auth_version IS '默认 1';

COMMENT ON COLUMN admin_users.last_login_at IS '最近登录';

CREATE TABLE admin_roles (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  code varchar(48) NOT NULL,
  name varchar(64) NOT NULL,
  data_scope varchar(24) NOT NULL,
  status varchar(16) NOT NULL
);

COMMENT ON TABLE admin_roles IS '后台角色';

COMMENT ON COLUMN admin_roles.code IS '角色编码';

COMMENT ON COLUMN admin_roles.name IS '名称';

COMMENT ON COLUMN admin_roles.data_scope IS 'ALL/ASSIGNED；首期只支持这两种';

COMMENT ON COLUMN admin_roles.status IS 'ACTIVE/DISABLED';

CREATE TABLE admin_permissions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  code varchar(96) NOT NULL,
  name varchar(64) NOT NULL,
  resource varchar(48) NOT NULL,
  action varchar(48) NOT NULL,
  sensitive boolean NOT NULL DEFAULT false
);

COMMENT ON TABLE admin_permissions IS '后台权限字典';

COMMENT ON COLUMN admin_permissions.code IS '如 refund.review/settlement.submit';

COMMENT ON COLUMN admin_permissions.name IS '权限名称';

COMMENT ON COLUMN admin_permissions.resource IS '资源类别';

COMMENT ON COLUMN admin_permissions.action IS '动作';

COMMENT ON COLUMN admin_permissions.sensitive IS '默认 false';

CREATE TABLE admin_user_roles (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  admin_id bigint NOT NULL,
  role_id bigint NOT NULL
);

COMMENT ON TABLE admin_user_roles IS '管理员角色关联';

COMMENT ON COLUMN admin_user_roles.admin_id IS '→admin_users';

COMMENT ON COLUMN admin_user_roles.role_id IS '→admin_roles';

CREATE TABLE admin_role_permissions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  role_id bigint NOT NULL,
  permission_id bigint NOT NULL
);

COMMENT ON TABLE admin_role_permissions IS '角色权限关联';

COMMENT ON COLUMN admin_role_permissions.role_id IS '→admin_roles';

COMMENT ON COLUMN admin_role_permissions.permission_id IS '→admin_permissions';

CREATE TABLE admin_approvals (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  operation varchar(48) NOT NULL,
  resource_type varchar(32) NOT NULL,
  resource_id bigint NOT NULL,
  requester_id bigint NOT NULL,
  reviewer_id bigint,
  payload_snapshot jsonb NOT NULL,
  payload_hash varchar(64) NOT NULL,
  resource_version integer NOT NULL,
  status varchar(16) NOT NULL,
  expires_at timestamptz NOT NULL,
  reviewed_at timestamptz,
  executed_at timestamptz
);

COMMENT ON TABLE admin_approvals IS '敏感操作双人复核';

COMMENT ON COLUMN admin_approvals.operation IS '操作代码';

COMMENT ON COLUMN admin_approvals.resource_type IS '资源类别';

COMMENT ON COLUMN admin_approvals.resource_id IS '业务资源 ID，逻辑关联';

COMMENT ON COLUMN admin_approvals.requester_id IS '→admin_users';

COMMENT ON COLUMN admin_approvals.reviewer_id IS '→admin_users';

COMMENT ON COLUMN admin_approvals.payload_snapshot IS '待批准参数快照';

COMMENT ON COLUMN admin_approvals.payload_hash IS '快照哈希';

COMMENT ON COLUMN admin_approvals.resource_version IS '提交时业务版本';

COMMENT ON COLUMN admin_approvals.status IS 'PENDING/APPROVED/REJECTED/EXPIRED/EXECUTED';

COMMENT ON COLUMN admin_approvals.expires_at IS '批准有效期';

COMMENT ON COLUMN admin_approvals.reviewed_at IS '复核时间';

COMMENT ON COLUMN admin_approvals.executed_at IS '实际执行时间';

CREATE TABLE admin_audit_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  actor_type varchar(16) NOT NULL,
  admin_id bigint,
  operation varchar(64) NOT NULL,
  resource_type varchar(32) NOT NULL,
  resource_id bigint NOT NULL,
  before_redacted jsonb NOT NULL DEFAULT '{}'::jsonb,
  after_redacted jsonb NOT NULL DEFAULT '{}'::jsonb,
  payload_asset_id bigint,
  request_id varchar(64) NOT NULL,
  ip inet,
  event_key varchar(160) NOT NULL,
  outcome varchar(16) NOT NULL
);

COMMENT ON TABLE admin_audit_logs IS '后台与系统敏感操作审计';

COMMENT ON COLUMN admin_audit_logs.actor_type IS 'ADMIN/SYSTEM';

COMMENT ON COLUMN admin_audit_logs.admin_id IS '→admin_users；系统任务为空';

COMMENT ON COLUMN admin_audit_logs.operation IS '动作';

COMMENT ON COLUMN admin_audit_logs.resource_type IS '对象类型';

COMMENT ON COLUMN admin_audit_logs.resource_id IS '对象 ID，逻辑关联';

COMMENT ON COLUMN admin_audit_logs.before_redacted IS '默认 {}；脱敏前值';

COMMENT ON COLUMN admin_audit_logs.after_redacted IS '默认 {}；脱敏后值';

COMMENT ON COLUMN admin_audit_logs.payload_asset_id IS '→media_assets；加密渠道报文引用';

COMMENT ON COLUMN admin_audit_logs.request_id IS '链路追踪';

COMMENT ON COLUMN admin_audit_logs.ip IS '来源 IP';

COMMENT ON COLUMN admin_audit_logs.event_key IS '唯一审计事件键';

COMMENT ON COLUMN admin_audit_logs.outcome IS 'SUCCESS/FAILED';

CREATE UNIQUE INDEX uq_admin_users_account ON admin_users (account);

CREATE UNIQUE INDEX uq_admin_roles_code ON admin_roles (code);

CREATE UNIQUE INDEX uq_admin_permissions_code ON admin_permissions (code);

CREATE UNIQUE INDEX uq_admin_permissions_resource_action ON admin_permissions (resource, action);

CREATE UNIQUE INDEX uq_admin_user_roles_admin_id_role_id ON admin_user_roles (admin_id, role_id);

CREATE UNIQUE INDEX uq_admin_role_permissions_role_id_permission_id ON admin_role_permissions (role_id, permission_id);

CREATE UNIQUE INDEX uq_admin_audit_logs_event_key ON admin_audit_logs (event_key);

CREATE INDEX ix_admin_user_roles_1 ON admin_user_roles (admin_id);

CREATE INDEX ix_admin_user_roles_2 ON admin_user_roles (role_id);

CREATE INDEX ix_admin_role_permissions_1 ON admin_role_permissions (role_id);

CREATE INDEX ix_admin_role_permissions_2 ON admin_role_permissions (permission_id);

CREATE INDEX ix_admin_approvals_1 ON admin_approvals (requester_id);

CREATE INDEX ix_admin_approvals_2 ON admin_approvals (reviewer_id);

CREATE INDEX ix_admin_audit_logs_1 ON admin_audit_logs (admin_id);

CREATE INDEX ix_admin_audit_logs_2 ON admin_audit_logs (payload_asset_id);

ALTER TABLE admin_users ADD CONSTRAINT ck_admin_users_status CHECK (status IN ('ACTIVE','DISABLED'));

ALTER TABLE admin_users ADD CONSTRAINT ck_admin_users_auth_version_positive CHECK (auth_version>0);

ALTER TABLE admin_roles ADD CONSTRAINT ck_admin_roles_data_scope CHECK (data_scope IN ('ALL','ASSIGNED'));

ALTER TABLE admin_roles ADD CONSTRAINT ck_admin_roles_status CHECK (status IN ('ACTIVE','DISABLED'));

ALTER TABLE admin_approvals ADD CONSTRAINT ck_admin_approvals_status CHECK (status IN ('PENDING','APPROVED','REJECTED','EXPIRED','EXECUTED'));

ALTER TABLE admin_audit_logs ADD CONSTRAINT ck_admin_audit_logs_actor_type CHECK (actor_type IN ('ADMIN','SYSTEM'));

ALTER TABLE admin_audit_logs ADD CONSTRAINT ck_admin_audit_logs_outcome CHECK (outcome IN ('SUCCESS','FAILED'));

ALTER TABLE admin_approvals ADD CONSTRAINT ck_approval_two_people CHECK (reviewer_id IS NULL OR reviewer_id<>requester_id);

ALTER TABLE admin_audit_logs ADD CONSTRAINT ck_audit_actor CHECK ((actor_type='ADMIN' AND admin_id IS NOT NULL) OR (actor_type='SYSTEM' AND admin_id IS NULL));

CREATE INDEX ix_admin_approvals_3 ON admin_approvals (status, created_at);

CREATE INDEX ix_admin_audit_logs_3 ON admin_audit_logs (resource_type, resource_id, created_at);

CREATE INDEX ix_admin_audit_logs_4 ON admin_audit_logs (admin_id, created_at);

ALTER TABLE admin_approvals ADD CONSTRAINT ck_json_admin_approvals_payload_snapshot CHECK (jsonb_typeof(payload_snapshot)='object');

ALTER TABLE admin_audit_logs ADD CONSTRAINT ck_json_admin_audit_logs_before_redacted CHECK (jsonb_typeof(before_redacted)='object');

ALTER TABLE admin_audit_logs ADD CONSTRAINT ck_json_admin_audit_logs_after_redacted CHECK (jsonb_typeof(after_redacted)='object');

CREATE TRIGGER tr_admin_audit_logs_append_only BEFORE UPDATE OR DELETE ON admin_audit_logs FOR EACH ROW EXECUTE FUNCTION dd_reject_event_mutation();

COMMIT;
