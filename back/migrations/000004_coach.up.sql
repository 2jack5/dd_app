ALTER TABLE coach_applications ADD CONSTRAINT ck_json_coach_applications_submitted_payload CHECK (jsonb_typeof(submitted_payload)='object');

ALTER TABLE coach_skills ADD CONSTRAINT ck_json_coach_skills_evidence_asset_ids CHECK (jsonb_typeof(evidence_asset_ids)='array');

COMMIT;
