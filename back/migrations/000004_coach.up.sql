-- 陪练入驻与认证
-- 按文件编号升序执行；本文件与对应 down 文件由迁移工具记录版本。
BEGIN;

CREATE TABLE coaches (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  user_id bigint NOT NULL,
  display_name varchar(64) NOT NULL,
  bio text NOT NULL DEFAULT '',
  status varchar(24) NOT NULL DEFAULT 'APPLYING',
  accepting_orders boolean NOT NULL DEFAULT false,
  last_active_at timestamptz,
  rating_sum bigint NOT NULL DEFAULT 0,
  rating_count bigint NOT NULL DEFAULT 0,
  completed_orders bigint NOT NULL DEFAULT 0,
  version integer NOT NULL DEFAULT 1,
  content_version integer NOT NULL DEFAULT 1
);

COMMENT ON TABLE coaches IS '陪练师档案';

COMMENT ON COLUMN coaches.user_id IS '→users';

COMMENT ON COLUMN coaches.display_name IS '已审核展示名';

COMMENT ON COLUMN coaches.bio IS '默认空；已审核简介';

COMMENT ON COLUMN coaches.status IS '默认 APPLYING；APPLYING/ACTIVE/SUSPENDED/REJECTED/CLOSED';

COMMENT ON COLUMN coaches.accepting_orders IS '默认 false；接单开关';

COMMENT ON COLUMN coaches.last_active_at IS '最近活跃；在线展示结合心跳 TTL';

COMMENT ON COLUMN coaches.rating_sum IS '默认 0；已公开主评星级和';

COMMENT ON COLUMN coaches.rating_count IS '默认 0；已公开主评数';

COMMENT ON COLUMN coaches.completed_orders IS '默认 0；完成订单数缓存';

COMMENT ON COLUMN coaches.version IS '默认 1';

COMMENT ON COLUMN coaches.content_version IS '默认 1；内容审核版本，提交新版本时递增；独立于登录或价格版本';

CREATE TABLE coach_applications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  coach_id bigint NOT NULL,
  revision integer NOT NULL,
  identity_check_id bigint,
  submitted_payload jsonb NOT NULL,
  status varchar(24) NOT NULL,
  submitted_at timestamptz,
  reviewer_id bigint,
  reviewed_at timestamptz,
  reject_reason text
);

COMMENT ON TABLE coach_applications IS '入驻申请历史';

COMMENT ON COLUMN coach_applications.coach_id IS '→coaches';

COMMENT ON COLUMN coach_applications.revision IS '申请版本，从 1 开始';

COMMENT ON COLUMN coach_applications.identity_check_id IS '→identity_checks';

COMMENT ON COLUMN coach_applications.submitted_payload IS '不可变申请资料及附件引用；敏感值不明文保存';

COMMENT ON COLUMN coach_applications.status IS 'DRAFT/SUBMITTED/REVIEWING/APPROVED/REJECTED/WITHDRAWN';

COMMENT ON COLUMN coach_applications.submitted_at IS '提交时间';

COMMENT ON COLUMN coach_applications.reviewer_id IS '→admin_users';

COMMENT ON COLUMN coach_applications.reviewed_at IS '审核时间';

COMMENT ON COLUMN coach_applications.reject_reason IS '拒绝原因';

CREATE TABLE identity_checks (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  user_id bigint NOT NULL,
  provider varchar(32) NOT NULL,
  provider_request_id varchar(128) NOT NULL,
  status varchar(24) NOT NULL,
  name_masked varchar(64),
  age_check_result varchar(24) NOT NULL,
  result_ref varchar(256),
  verified_at timestamptz,
  expires_at timestamptz,
  reviewer_id bigint,
  review_note text,
  revoked_at timestamptz,
  revoke_reason text
);

COMMENT ON TABLE identity_checks IS '实名核验记录';

COMMENT ON COLUMN identity_checks.user_id IS '→users';

COMMENT ON COLUMN identity_checks.provider IS '核验渠道';

COMMENT ON COLUMN identity_checks.provider_request_id IS '渠道请求号';

COMMENT ON COLUMN identity_checks.status IS 'PENDING/PASSED/FAILED/EXPIRED/REVOKED';

COMMENT ON COLUMN identity_checks.name_masked IS '脱敏姓名';

COMMENT ON COLUMN identity_checks.age_check_result IS 'UNKNOWN/ELIGIBLE/INELIGIBLE；年龄阈值按规则';

COMMENT ON COLUMN identity_checks.result_ref IS '渠道结果引用';

COMMENT ON COLUMN identity_checks.verified_at IS '成功时间';

COMMENT ON COLUMN identity_checks.expires_at IS '有效期';

COMMENT ON COLUMN identity_checks.reviewer_id IS '→admin_users';

COMMENT ON COLUMN identity_checks.review_note IS '脱敏复核意见';

COMMENT ON COLUMN identity_checks.revoked_at IS '核验明确撤销时间；普通失败重试不自动撤销旧通过';

COMMENT ON COLUMN identity_checks.revoke_reason IS '撤销原因';

CREATE TABLE coach_skills (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  coach_id bigint NOT NULL,
  game_id bigint NOT NULL,
  rank_id bigint NOT NULL,
  revision integer NOT NULL,
  status varchar(24) NOT NULL,
  is_current boolean NOT NULL DEFAULT false,
  evidence_asset_ids jsonb NOT NULL DEFAULT '[]'::jsonb,
  reviewer_id bigint,
  review_note text,
  verified_at timestamptz,
  expires_at timestamptz
);

COMMENT ON TABLE coach_skills IS '游戏技能认证版本';

COMMENT ON COLUMN coach_skills.coach_id IS '→coaches';

COMMENT ON COLUMN coach_skills.game_id IS '→games';

COMMENT ON COLUMN coach_skills.rank_id IS '→game_ranks；须属于 game_id';

COMMENT ON COLUMN coach_skills.revision IS '同陪练同游戏递增';

COMMENT ON COLUMN coach_skills.status IS 'DRAFT/SUBMITTED/REVIEWING/APPROVED/REJECTED/EXPIRED';

COMMENT ON COLUMN coach_skills.is_current IS '默认 false；当前有效通过版本';

COMMENT ON COLUMN coach_skills.evidence_asset_ids IS '默认 []；私有证明资源 ID 数组';

COMMENT ON COLUMN coach_skills.reviewer_id IS '→admin_users';

COMMENT ON COLUMN coach_skills.review_note IS '审核意见';

COMMENT ON COLUMN coach_skills.verified_at IS '认证通过时间';

COMMENT ON COLUMN coach_skills.expires_at IS '认证有效期';

CREATE UNIQUE INDEX uq_coaches_user_id ON coaches (user_id);

CREATE UNIQUE INDEX uq_coach_applications_coach_id_revision ON coach_applications (coach_id, revision);

CREATE UNIQUE INDEX uq_identity_checks_provider_provider_request_id ON identity_checks (provider, provider_request_id);

CREATE UNIQUE INDEX uq_coach_skills_coach_id_game_id_revision ON coach_skills (coach_id, game_id, revision);

CREATE UNIQUE INDEX uq_coach_applications_coach_id ON coach_applications (coach_id) WHERE status IN ('SUBMITTED','REVIEWING');

CREATE UNIQUE INDEX uq_coach_skills_coach_id_game_id ON coach_skills (coach_id, game_id) WHERE is_current;

CREATE INDEX ix_coach_applications_1 ON coach_applications (coach_id);

CREATE INDEX ix_coach_applications_2 ON coach_applications (identity_check_id);

CREATE INDEX ix_coach_applications_3 ON coach_applications (reviewer_id);

CREATE INDEX ix_identity_checks_1 ON identity_checks (user_id);

CREATE INDEX ix_identity_checks_2 ON identity_checks (reviewer_id);

CREATE INDEX ix_coach_skills_1 ON coach_skills (coach_id);

CREATE INDEX ix_coach_skills_2 ON coach_skills (game_id);

CREATE INDEX ix_coach_skills_3 ON coach_skills (rank_id);

CREATE INDEX ix_coach_skills_4 ON coach_skills (reviewer_id);

ALTER TABLE coaches ADD CONSTRAINT ck_coaches_status CHECK (status IN ('APPLYING','ACTIVE','SUSPENDED','REJECTED','CLOSED'));

ALTER TABLE coaches ADD CONSTRAINT ck_coaches_version_positive CHECK (version>0);

ALTER TABLE coaches ADD CONSTRAINT ck_coaches_content_version_positive CHECK (content_version>0);

ALTER TABLE coach_applications ADD CONSTRAINT ck_coach_applications_revision_positive CHECK (revision>0);

ALTER TABLE coach_applications ADD CONSTRAINT ck_coach_applications_status CHECK (status IN ('DRAFT','SUBMITTED','REVIEWING','APPROVED','REJECTED','WITHDRAWN'));

ALTER TABLE identity_checks ADD CONSTRAINT ck_identity_checks_status CHECK (status IN ('PENDING','PASSED','FAILED','EXPIRED','REVOKED'));

ALTER TABLE identity_checks ADD CONSTRAINT ck_identity_checks_age_check_result CHECK (age_check_result IN ('UNKNOWN','ELIGIBLE','INELIGIBLE'));

ALTER TABLE coach_skills ADD CONSTRAINT ck_coach_skills_revision_positive CHECK (revision>0);

ALTER TABLE coach_skills ADD CONSTRAINT ck_coach_skills_status CHECK (status IN ('DRAFT','SUBMITTED','REVIEWING','APPROVED','REJECTED','EXPIRED'));

ALTER TABLE coaches ADD CONSTRAINT ck_coach_counters CHECK (rating_count>=0 AND rating_sum>=rating_count AND rating_sum<=5*rating_count AND completed_orders>=0);

ALTER TABLE identity_checks ADD CONSTRAINT ck_identity_expiry CHECK (expires_at IS NULL OR verified_at IS NULL OR expires_at>verified_at);

ALTER TABLE identity_checks ADD CONSTRAINT ck_identity_revoked CHECK ((status='REVOKED')=(revoked_at IS NOT NULL));

ALTER TABLE coach_skills ADD CONSTRAINT ck_skill_current CHECK (NOT is_current OR status='APPROVED');

CREATE INDEX ix_coaches_2 ON coaches (status, accepting_orders, id);

CREATE INDEX ix_coach_applications_4 ON coach_applications (status, submitted_at);

