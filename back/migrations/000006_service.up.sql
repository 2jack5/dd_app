-- 服务商品、排期与预约占位
-- 按文件编号升序执行；本文件与对应 down 文件由迁移工具记录版本。
BEGIN;

CREATE TABLE coach_services (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  coach_id bigint NOT NULL,
  game_id bigint NOT NULL,
  category_id bigint NOT NULL,
  title varchar(128) NOT NULL,
  description text NOT NULL,
  unit_type varchar(16) NOT NULL,
  billing_minutes integer,
  booking_minutes_per_unit integer NOT NULL,
  price_cent bigint NOT NULL,
  min_qty integer NOT NULL DEFAULT 1,
  max_qty integer NOT NULL,
  status varchar(24) NOT NULL,
  version integer NOT NULL DEFAULT 1,
  content_version integer NOT NULL DEFAULT 1
);

COMMENT ON TABLE coach_services IS '陪练服务商品';

COMMENT ON COLUMN coach_services.coach_id IS '→coaches';

COMMENT ON COLUMN coach_services.game_id IS '→games';

COMMENT ON COLUMN coach_services.category_id IS '→service_categories；复合外键保证游戏一致';

COMMENT ON COLUMN coach_services.title IS '已审核标题';

COMMENT ON COLUMN coach_services.description IS '已审核服务介绍';

COMMENT ON COLUMN coach_services.unit_type IS 'HOUR/ROUND；计价单位，从分类复制，发布后不可直接改变含义';

COMMENT ON COLUMN coach_services.billing_minutes IS '从分类复制，订单再快照';

COMMENT ON COLUMN coach_services.booking_minutes_per_unit IS '每单位预计占用分钟，>0；按局也必须配置';

COMMENT ON COLUMN coach_services.price_cent IS '单位价格，>0';

COMMENT ON COLUMN coach_services.min_qty IS '默认 1，>0';

COMMENT ON COLUMN coach_services.max_qty IS '>=min_qty';

COMMENT ON COLUMN coach_services.status IS 'DRAFT/ON_SHELF/OFF_SHELF/BLOCKED';

COMMENT ON COLUMN coach_services.version IS '默认 1；改价、可售范围修改递增';

COMMENT ON COLUMN coach_services.content_version IS '默认 1；内容审核版本，提交新版本时递增；独立于登录或价格版本';

CREATE TABLE coach_service_regions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  service_id bigint NOT NULL,
  game_id bigint NOT NULL,
  region_id bigint NOT NULL
);

COMMENT ON TABLE coach_service_regions IS '服务可售区服';

COMMENT ON COLUMN coach_service_regions.service_id IS '→coach_services';

COMMENT ON COLUMN coach_service_regions.game_id IS '→games；用于同游戏约束';

COMMENT ON COLUMN coach_service_regions.region_id IS '→game_regions';

CREATE TABLE coach_availability (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  coach_id bigint NOT NULL,
  start_at timestamptz NOT NULL,
  end_at timestamptz NOT NULL,
  status varchar(16) NOT NULL,
  version integer NOT NULL DEFAULT 1
);

COMMENT ON TABLE coach_availability IS '可预约排期';

COMMENT ON COLUMN coach_availability.coach_id IS '→coaches';

COMMENT ON COLUMN coach_availability.start_at IS '可用开始';

COMMENT ON COLUMN coach_availability.end_at IS '可用结束';

COMMENT ON COLUMN coach_availability.status IS 'OPEN/CLOSED';

COMMENT ON COLUMN coach_availability.version IS '默认 1';

CREATE TABLE booking_holds (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  coach_id bigint NOT NULL,
  order_id bigint NOT NULL,
  start_at timestamptz NOT NULL,
  end_at timestamptz NOT NULL,
  status varchar(16) NOT NULL,
  expires_at timestamptz,
  released_at timestamptz
);

COMMENT ON TABLE booking_holds IS '预约预占与已占库存';

COMMENT ON COLUMN booking_holds.coach_id IS '→coaches';

COMMENT ON COLUMN booking_holds.order_id IS '→orders';

COMMENT ON COLUMN booking_holds.start_at IS '预约开始';

COMMENT ON COLUMN booking_holds.end_at IS '预约结束；半开区间';

COMMENT ON COLUMN booking_holds.status IS 'HELD/CONFIRMED/RELEASED/EXPIRED';

COMMENT ON COLUMN booking_holds.expires_at IS '待支付占用的失效检查时间';

COMMENT ON COLUMN booking_holds.released_at IS '释放时间';

CREATE UNIQUE INDEX uq_coach_services_id_game_id ON coach_services (id, game_id);

CREATE UNIQUE INDEX uq_coach_services_id_game_id_coach_id ON coach_services (id, game_id, coach_id);

CREATE UNIQUE INDEX uq_coach_service_regions_service_id_region_id ON coach_service_regions (service_id, region_id);

CREATE UNIQUE INDEX uq_booking_holds_order_id ON booking_holds (order_id);

CREATE INDEX ix_coach_services_1 ON coach_services (coach_id);

CREATE INDEX ix_coach_services_2 ON coach_services (game_id);

CREATE INDEX ix_coach_services_3 ON coach_services (category_id);

CREATE INDEX ix_coach_service_regions_1 ON coach_service_regions (service_id);

CREATE INDEX ix_coach_service_regions_2 ON coach_service_regions (game_id);

CREATE INDEX ix_coach_service_regions_3 ON coach_service_regions (region_id);

CREATE INDEX ix_coach_availability_1 ON coach_availability (coach_id);

CREATE INDEX ix_booking_holds_1 ON booking_holds (coach_id);

ALTER TABLE coach_services ADD CONSTRAINT ck_coach_services_unit_type CHECK (unit_type IN ('HOUR','ROUND'));

ALTER TABLE coach_services ADD CONSTRAINT ck_coach_services_status CHECK (status IN ('DRAFT','ON_SHELF','OFF_SHELF','BLOCKED'));

ALTER TABLE coach_services ADD CONSTRAINT ck_coach_services_version_positive CHECK (version>0);

ALTER TABLE coach_services ADD CONSTRAINT ck_coach_services_content_version_positive CHECK (content_version>0);

ALTER TABLE coach_availability ADD CONSTRAINT ck_coach_availability_status CHECK (status IN ('OPEN','CLOSED'));

ALTER TABLE coach_availability ADD CONSTRAINT ck_coach_availability_version_positive CHECK (version>0);

ALTER TABLE booking_holds ADD CONSTRAINT ck_booking_holds_status CHECK (status IN ('HELD','CONFIRMED','RELEASED','EXPIRED'));

ALTER TABLE coach_services ADD CONSTRAINT ck_service_price_qty CHECK (price_cent>0 AND min_qty>0 AND max_qty>=min_qty AND booking_minutes_per_unit>0);

ALTER TABLE coach_services ADD CONSTRAINT ck_service_billing CHECK ((unit_type='HOUR' AND billing_minutes IS NOT NULL AND billing_minutes>0) OR (unit_type='ROUND' AND billing_minutes IS NULL));

ALTER TABLE coach_availability ADD CONSTRAINT ck_availability_time CHECK (start_at<end_at);

ALTER TABLE booking_holds ADD CONSTRAINT ck_booking_time CHECK (start_at<end_at);

ALTER TABLE booking_holds ADD CONSTRAINT ck_held_expiry CHECK (status<>'HELD' OR expires_at IS NOT NULL);

ALTER TABLE booking_holds ADD CONSTRAINT ex_booking_holds EXCLUDE USING gist (coach_id WITH =, tstzrange(start_at,end_at,'[)') WITH &&) WHERE (status IN ('HELD','CONFIRMED'));

ALTER TABLE coach_availability ADD CONSTRAINT ex_coach_availability EXCLUDE USING gist (coach_id WITH =, tstzrange(start_at,end_at,'[)') WITH &&) WHERE (status='OPEN');

CREATE INDEX ix_coach_services_4 ON coach_services (game_id, status, price_cent, id);

CREATE INDEX ix_coach_services_5 ON coach_services (coach_id, status);

CREATE INDEX ix_coach_availability_2 ON coach_availability (coach_id, start_at, end_at);

CREATE INDEX ix_booking_holds_3 ON booking_holds (status, expires_at);

COMMIT;
