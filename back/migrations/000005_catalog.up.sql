-- 游戏、区服、段位与服务分类
-- 按文件编号升序执行；本文件与对应 down 文件由迁移工具记录版本。
BEGIN;

CREATE TABLE games (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  code varchar(48) NOT NULL,
  name varchar(64) NOT NULL,
  icon_asset_id bigint,
  keywords text NOT NULL DEFAULT '',
  status varchar(16) NOT NULL,
  sort_order integer NOT NULL DEFAULT 0
);

COMMENT ON TABLE games IS '游戏目录';

COMMENT ON COLUMN games.code IS '稳定业务编码';

COMMENT ON COLUMN games.name IS '游戏名';

COMMENT ON COLUMN games.icon_asset_id IS '→media_assets';

COMMENT ON COLUMN games.keywords IS '默认空；搜索别名';

COMMENT ON COLUMN games.status IS 'ENABLED/DISABLED';

COMMENT ON COLUMN games.sort_order IS '默认 0';

CREATE TABLE game_regions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  game_id bigint NOT NULL,
  code varchar(48) NOT NULL,
  name varchar(64) NOT NULL,
  status varchar(16) NOT NULL,
  sort_order integer NOT NULL DEFAULT 0
);

COMMENT ON TABLE game_regions IS '游戏区服';

COMMENT ON COLUMN game_regions.game_id IS '→games';

COMMENT ON COLUMN game_regions.code IS '区服编码';

COMMENT ON COLUMN game_regions.name IS '展示名';

COMMENT ON COLUMN game_regions.status IS 'ENABLED/DISABLED';

COMMENT ON COLUMN game_regions.sort_order IS '默认 0';

CREATE TABLE game_ranks (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  game_id bigint NOT NULL,
  code varchar(48) NOT NULL,
  name varchar(64) NOT NULL,
  rank_level integer NOT NULL,
  status varchar(16) NOT NULL
);

COMMENT ON TABLE game_ranks IS '游戏段位字典';

COMMENT ON COLUMN game_ranks.game_id IS '→games';

COMMENT ON COLUMN game_ranks.code IS '段位编码';

COMMENT ON COLUMN game_ranks.name IS '如王者/钻石';

COMMENT ON COLUMN game_ranks.rank_level IS '排序等级';

COMMENT ON COLUMN game_ranks.status IS 'ENABLED/DISABLED';

CREATE TABLE service_categories (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  game_id bigint NOT NULL,
  code varchar(48) NOT NULL,
  name varchar(64) NOT NULL,
  unit_type varchar(16) NOT NULL,
  billing_minutes integer,
  min_price_cent bigint NOT NULL,
  max_price_cent bigint NOT NULL,
  status varchar(16) NOT NULL,
  sort_order integer NOT NULL DEFAULT 0
);

COMMENT ON TABLE service_categories IS '服务分类与价格边界';

COMMENT ON COLUMN service_categories.game_id IS '→games';

COMMENT ON COLUMN service_categories.code IS '分类编码';

COMMENT ON COLUMN service_categories.name IS '服务名';

COMMENT ON COLUMN service_categories.unit_type IS 'HOUR/ROUND';

COMMENT ON COLUMN service_categories.billing_minutes IS '小时类一个计价单位的分钟数，如 30/60；局类 NULL';

COMMENT ON COLUMN service_categories.min_price_cent IS '最低单价，>0';

COMMENT ON COLUMN service_categories.max_price_cent IS '最高单价，>=最低单价';

COMMENT ON COLUMN service_categories.status IS 'ENABLED/DISABLED';

COMMENT ON COLUMN service_categories.sort_order IS '默认 0';

CREATE UNIQUE INDEX uq_games_code ON games (code);

CREATE UNIQUE INDEX uq_game_regions_game_id_code ON game_regions (game_id, code);

CREATE UNIQUE INDEX uq_game_regions_id_game_id ON game_regions (id, game_id);

CREATE UNIQUE INDEX uq_game_ranks_game_id_code ON game_ranks (game_id, code);

CREATE UNIQUE INDEX uq_game_ranks_id_game_id ON game_ranks (id, game_id);

CREATE UNIQUE INDEX uq_service_categories_game_id_code_unit_type ON service_categories (game_id, code, unit_type);

CREATE UNIQUE INDEX uq_service_categories_id_game_id ON service_categories (id, game_id);

CREATE INDEX ix_games_1 ON games (icon_asset_id);

CREATE INDEX ix_game_regions_1 ON game_regions (game_id);

CREATE INDEX ix_game_ranks_1 ON game_ranks (game_id);

CREATE INDEX ix_service_categories_1 ON service_categories (game_id);

ALTER TABLE games ADD CONSTRAINT ck_games_status CHECK (status IN ('ENABLED','DISABLED'));

ALTER TABLE game_regions ADD CONSTRAINT ck_game_regions_status CHECK (status IN ('ENABLED','DISABLED'));

ALTER TABLE game_ranks ADD CONSTRAINT ck_game_ranks_status CHECK (status IN ('ENABLED','DISABLED'));

ALTER TABLE service_categories ADD CONSTRAINT ck_service_categories_unit_type CHECK (unit_type IN ('HOUR','ROUND'));

ALTER TABLE service_categories ADD CONSTRAINT ck_service_categories_status CHECK (status IN ('ENABLED','DISABLED'));

ALTER TABLE service_categories ADD CONSTRAINT ck_category_prices CHECK (min_price_cent>0 AND max_price_cent>=min_price_cent);

ALTER TABLE service_categories ADD CONSTRAINT ck_category_billing CHECK ((unit_type='HOUR' AND billing_minutes IS NOT NULL AND billing_minutes>0) OR (unit_type='ROUND' AND billing_minutes IS NULL));

CREATE INDEX ix_games_2 ON games (status, sort_order, id);

CREATE INDEX ix_game_ranks_2 ON game_ranks (game_id, rank_level);

COMMIT;
