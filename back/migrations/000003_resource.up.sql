-- 文件资源与通知
-- 按文件编号升序执行；本文件与对应 down 文件由迁移工具记录版本。
BEGIN;

CREATE TABLE media_assets (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  owner_user_id bigint,
  uploaded_by_admin_id bigint,
  storage_key varchar(512) NOT NULL,
  mime_type varchar(128) NOT NULL,
  size_bytes bigint NOT NULL,
  sha256 varchar(64) NOT NULL,
  purpose varchar(32) NOT NULL,
  access_scope varchar(16) NOT NULL,
  status varchar(24) NOT NULL,
  retention_until timestamptz
);

COMMENT ON TABLE media_assets IS '文件与证据资源';

COMMENT ON COLUMN media_assets.owner_user_id IS '→users；系统文件可空';

COMMENT ON COLUMN media_assets.uploaded_by_admin_id IS '→admin_users';

COMMENT ON COLUMN media_assets.storage_key IS '私有对象键';

COMMENT ON COLUMN media_assets.mime_type IS '类型';

COMMENT ON COLUMN media_assets.size_bytes IS '文件大小，>=0';

COMMENT ON COLUMN media_assets.sha256 IS '文件摘要';

COMMENT ON COLUMN media_assets.purpose IS 'AVATAR/SKILL/REVIEW/CASE/BILL/AGREEMENT/CHANNEL_PAYLOAD/GAME_ICON/BANNER/ACTIVITY_COVER/SERVICE_IMAGE';

COMMENT ON COLUMN media_assets.access_scope IS 'PRIVATE/PUBLIC';

COMMENT ON COLUMN media_assets.status IS 'UPLOADING/PENDING/APPROVED/REJECTED/DELETED';

COMMENT ON COLUMN media_assets.retention_until IS '保留到期日';

CREATE TABLE notifications (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  user_id bigint NOT NULL,
  biz_type varchar(32) NOT NULL,
  biz_id bigint NOT NULL,
  template_code varchar(64) NOT NULL,
  payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  channel varchar(24) NOT NULL,
  status varchar(24) NOT NULL,
  read_at timestamptz,
  sent_at timestamptz,
  retry_count integer NOT NULL DEFAULT 0,
  dedupe_key varchar(160) NOT NULL
);

COMMENT ON TABLE notifications IS '业务通知';

COMMENT ON COLUMN notifications.user_id IS '→users';

COMMENT ON COLUMN notifications.biz_type IS 'APPLICATION/ORDER/REFUND/CASE/SETTLEMENT';

COMMENT ON COLUMN notifications.biz_id IS '对应业务记录，逻辑关联';

COMMENT ON COLUMN notifications.template_code IS '消息模板';

COMMENT ON COLUMN notifications.payload IS '默认 {}；脱敏模板参数';

COMMENT ON COLUMN notifications.channel IS 'IN_APP/WECHAT_SUBSCRIBE';

COMMENT ON COLUMN notifications.status IS 'PENDING/SENT/FAILED';

COMMENT ON COLUMN notifications.read_at IS '站内已读时间';

COMMENT ON COLUMN notifications.sent_at IS '发送时间';

COMMENT ON COLUMN notifications.retry_count IS '默认 0';

COMMENT ON COLUMN notifications.dedupe_key IS '同一业务事件每渠道唯一';

CREATE UNIQUE INDEX uq_media_assets_storage_key ON media_assets (storage_key);

CREATE UNIQUE INDEX uq_notifications_dedupe_key ON notifications (dedupe_key);

CREATE INDEX ix_media_assets_1 ON media_assets (owner_user_id);

CREATE INDEX ix_media_assets_2 ON media_assets (uploaded_by_admin_id);

CREATE INDEX ix_notifications_1 ON notifications (user_id);

ALTER TABLE media_assets ADD CONSTRAINT ck_media_assets_purpose CHECK (purpose IN ('AVATAR','SKILL','REVIEW','CASE','BILL','AGREEMENT','CHANNEL_PAYLOAD','GAME_ICON','BANNER','ACTIVITY_COVER','SERVICE_IMAGE'));

ALTER TABLE media_assets ADD CONSTRAINT ck_media_assets_access_scope CHECK (access_scope IN ('PRIVATE','PUBLIC'));

ALTER TABLE media_assets ADD CONSTRAINT ck_media_assets_status CHECK (status IN ('UPLOADING','PENDING','APPROVED','REJECTED','DELETED'));

ALTER TABLE notifications ADD CONSTRAINT ck_notifications_biz_type CHECK (biz_type IN ('APPLICATION','ORDER','REFUND','CASE','SETTLEMENT','SETTLEMENT_SUPPLEMENT'));

ALTER TABLE notifications ADD CONSTRAINT ck_notifications_channel CHECK (channel IN ('IN_APP','WECHAT_SUBSCRIBE'));

ALTER TABLE notifications ADD CONSTRAINT ck_notifications_status CHECK (status IN ('PENDING','SENT','FAILED'));

ALTER TABLE media_assets ADD CONSTRAINT ck_asset_size CHECK (size_bytes>=0);

ALTER TABLE media_assets ADD CONSTRAINT ck_channel_payload_private CHECK (purpose <> 'CHANNEL_PAYLOAD' OR access_scope='PRIVATE');

ALTER TABLE notifications ADD CONSTRAINT ck_notification_retries CHECK (retry_count>=0);

CREATE INDEX ix_notifications_2 ON notifications (user_id, created_at DESC);

CREATE INDEX ix_notifications_3 ON notifications (status, created_at);

ALTER TABLE notifications ADD CONSTRAINT ck_json_notifications_payload CHECK (jsonb_typeof(payload)='object');

COMMIT;
