ALTER TABLE orders ADD CONSTRAINT ck_orders_status CHECK (status IN ('PENDING_PAYMENT','WAIT_ACCEPT','WAIT_START','IN_SERVICE','WAIT_CONFIRM','COMPLETED','CLOSED'));

