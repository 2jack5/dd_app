-- 报价、订单与订单事件
-- 按文件编号升序执行；本文件与对应 down 文件由迁移工具记录版本。
BEGIN;

CREATE TABLE order_quotes (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  quote_no varchar(64) NOT NULL,
  buyer_id bigint NOT NULL,
  service_id bigint NOT NULL,
  service_version integer NOT NULL,
  region_id bigint NOT NULL,
  quantity integer NOT NULL,
  start_at timestamptz NOT NULL,
  end_at timestamptz NOT NULL,
  amount_cent bigint NOT NULL,
  snapshot jsonb NOT NULL,
  status varchar(16) NOT NULL,
  expires_at timestamptz NOT NULL
);

COMMENT ON TABLE order_quotes IS '订单报价';

COMMENT ON COLUMN order_quotes.quote_no IS '不可猜报价号';

COMMENT ON COLUMN order_quotes.buyer_id IS '→users';

COMMENT ON COLUMN order_quotes.service_id IS '→coach_services';

COMMENT ON COLUMN order_quotes.service_version IS '报价时服务版本';

COMMENT ON COLUMN order_quotes.region_id IS '→game_regions';

COMMENT ON COLUMN order_quotes.quantity IS '计价单位数量，>0';

COMMENT ON COLUMN order_quotes.start_at IS '预约开始';

COMMENT ON COLUMN order_quotes.end_at IS '服务端算出的预计结束';

COMMENT ON COLUMN order_quotes.amount_cent IS '报价总价，>0';

COMMENT ON COLUMN order_quotes.snapshot IS '服务、单价、计价规则、佣金及业务规则版本';

COMMENT ON COLUMN order_quotes.status IS 'VALID/CONSUMED/EXPIRED';

COMMENT ON COLUMN order_quotes.expires_at IS '报价过期时间';

CREATE TABLE orders (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  order_no varchar(40) NOT NULL,
  quote_id bigint NOT NULL,
  buyer_id bigint NOT NULL,
  coach_id bigint NOT NULL,
  service_id bigint NOT NULL,
  game_id bigint NOT NULL,
  region_id bigint NOT NULL,
  status varchar(24) NOT NULL DEFAULT 'PENDING_PAYMENT',
  quantity integer NOT NULL,
  unit_price_cent bigint NOT NULL,
  total_cent bigint NOT NULL,
  currency char(3) NOT NULL DEFAULT 'CNY',
  commission_bps integer NOT NULL,
  commission_cent bigint NOT NULL,
  coach_income_cent bigint NOT NULL,
  commission_rule_id bigint NOT NULL,
  business_rule_id bigint NOT NULL,
  service_snapshot jsonb NOT NULL,
  appointment_start_at timestamptz NOT NULL,
  appointment_end_at timestamptz NOT NULL,
  game_player_id_cipher bytea NOT NULL,
  remark varchar(512) NOT NULL DEFAULT '',
  pay_deadline_at timestamptz NOT NULL,
  accept_deadline_at timestamptz,
  accepted_at timestamptz,
  started_at timestamptz,
  submitted_complete_at timestamptz,
  auto_confirm_at timestamptz,
  completed_at timestamptz,
  closed_at timestamptz,
  close_reason varchar(64),
  dispute_status varchar(16) NOT NULL DEFAULT 'NONE',
  version integer NOT NULL DEFAULT 1
);

COMMENT ON TABLE orders IS '业务订单';

COMMENT ON COLUMN orders.order_no IS '业务订单号';

COMMENT ON COLUMN orders.quote_id IS '→order_quotes';

COMMENT ON COLUMN orders.buyer_id IS '→users';

COMMENT ON COLUMN orders.coach_id IS '→coaches';

COMMENT ON COLUMN orders.service_id IS '→coach_services';

COMMENT ON COLUMN orders.game_id IS '→games';

COMMENT ON COLUMN orders.region_id IS '→game_regions';

COMMENT ON COLUMN orders.status IS '默认 PENDING_PAYMENT；PENDING_PAYMENT/WAIT_ACCEPT/WAIT_START/IN_SERVICE/WAIT_CONFIRM/COMPLETED/CLOSED';

COMMENT ON COLUMN orders.quantity IS '>0';

COMMENT ON COLUMN orders.unit_price_cent IS '成交单价，>0';

COMMENT ON COLUMN orders.total_cent IS '总价；首期无优惠=单价×数量';

COMMENT ON COLUMN orders.currency IS '默认 CNY';

COMMENT ON COLUMN orders.commission_bps IS '0..10000；万分比快照';

COMMENT ON COLUMN orders.commission_cent IS '订单初始佣金';

COMMENT ON COLUMN orders.coach_income_cent IS '初始理论应得=总额-佣金';

COMMENT ON COLUMN orders.commission_rule_id IS '→commission_rules';

COMMENT ON COLUMN orders.business_rule_id IS '→business_rule_versions';

COMMENT ON COLUMN orders.service_snapshot IS '不可变展示和计价快照';

COMMENT ON COLUMN orders.appointment_start_at IS '预约开始';

COMMENT ON COLUMN orders.appointment_end_at IS '预约结束';

COMMENT ON COLUMN orders.game_player_id_cipher IS '游戏 ID/角色名密文';

COMMENT ON COLUMN orders.remark IS '默认空；限制隐私内容';

COMMENT ON COLUMN orders.pay_deadline_at IS '支付截止';

COMMENT ON COLUMN orders.accept_deadline_at IS '支付后生成接单截止';

COMMENT ON COLUMN orders.accepted_at IS '接单时间';

COMMENT ON COLUMN orders.started_at IS '真实开始时间';

COMMENT ON COLUMN orders.submitted_complete_at IS '提交完成时间';

COMMENT ON COLUMN orders.auto_confirm_at IS '允许自动确认时间';

COMMENT ON COLUMN orders.completed_at IS '确认完成时间';

COMMENT ON COLUMN orders.closed_at IS '关闭时间';

COMMENT ON COLUMN orders.close_reason IS '取消、拒单、超时等原因';

COMMENT ON COLUMN orders.dispute_status IS '默认 NONE；NONE/OPEN/RESOLVED';

COMMENT ON COLUMN orders.version IS '默认 1';

CREATE TABLE order_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  order_id bigint NOT NULL,
  from_status varchar(24),
  to_status varchar(24) NOT NULL,
  event_type varchar(48) NOT NULL,
  actor_type varchar(16) NOT NULL,
  actor_id bigint,
  request_id varchar(64) NOT NULL,
  event_key varchar(160) NOT NULL,
  payload jsonb NOT NULL DEFAULT '{}'::jsonb
);

COMMENT ON TABLE order_events IS '订单事件时间轴';

COMMENT ON COLUMN order_events.order_id IS '→orders';

COMMENT ON COLUMN order_events.from_status IS '原履约态';

COMMENT ON COLUMN order_events.to_status IS '目标履约态，可与原态相同';

COMMENT ON COLUMN order_events.event_type IS '事件代码';

COMMENT ON COLUMN order_events.actor_type IS 'USER/COACH/ADMIN/SYSTEM';

COMMENT ON COLUMN order_events.actor_id IS '对应用户或管理员；SYSTEM 可空';

COMMENT ON COLUMN order_events.request_id IS '链路追踪号，不单独唯一';

COMMENT ON COLUMN order_events.event_key IS '全局事件幂等键';

COMMENT ON COLUMN order_events.payload IS '默认 {}；取消原因、退款引用、履约证据 ID 等';

