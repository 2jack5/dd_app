-- 支付、退款及资金事件
-- 按文件编号升序执行；本文件与对应 down 文件由迁移工具记录版本。
BEGIN;

CREATE TABLE payments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  order_id bigint NOT NULL,
  provider varchar(32) NOT NULL,
  merchant_id varchar(64) NOT NULL,
  app_id varchar(64) NOT NULL,
  out_trade_no varchar(64) NOT NULL,
  transaction_id varchar(128),
  amount_cent bigint NOT NULL,
  currency char(3) NOT NULL DEFAULT 'CNY',
  status varchar(24) NOT NULL,
  prepay_ref_cipher bytea,
  paid_at timestamptz,
  refund_reserved_cent bigint NOT NULL DEFAULT 0,
  refunded_cent bigint NOT NULL DEFAULT 0,
  version integer NOT NULL DEFAULT 1
);

COMMENT ON TABLE payments IS '逻辑支付单';

COMMENT ON COLUMN payments.order_id IS '→orders';

COMMENT ON COLUMN payments.provider IS '渠道适配器代码';

COMMENT ON COLUMN payments.merchant_id IS '商户标识';

COMMENT ON COLUMN payments.app_id IS '发起支付应用';

COMMENT ON COLUMN payments.out_trade_no IS '商户单号';

COMMENT ON COLUMN payments.transaction_id IS '渠道交易号；未支付为 NULL';

COMMENT ON COLUMN payments.amount_cent IS '应付总额，>0';

COMMENT ON COLUMN payments.currency IS '默认 CNY';

COMMENT ON COLUMN payments.status IS 'UNPAID/PREPAY_CREATED/PAID/CLOSING/CLOSED/FAILED';

COMMENT ON COLUMN payments.prepay_ref_cipher IS '预支付引用密文';

COMMENT ON COLUMN payments.paid_at IS '渠道真实支付时间';

COMMENT ON COLUMN payments.refund_reserved_cent IS '默认 0；已预留但未成功退款额';

COMMENT ON COLUMN payments.refunded_cent IS '默认 0；成功退款累计';

COMMENT ON COLUMN payments.version IS '默认 1';

CREATE TABLE payment_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  payment_id bigint,
  provider varchar(32) NOT NULL,
  merchant_id varchar(64) NOT NULL,
  event_key varchar(160) NOT NULL,
  event_type varchar(48) NOT NULL,
  payload_digest varchar(64) NOT NULL,
  payload_asset_id bigint,
  status varchar(16) NOT NULL,
  error_code varchar(64),
  handled_at timestamptz
);

COMMENT ON TABLE payment_events IS '支付通知与查单事实';

COMMENT ON COLUMN payment_events.payment_id IS '→payments；未匹配回调可空';

COMMENT ON COLUMN payment_events.provider IS '渠道';

COMMENT ON COLUMN payment_events.merchant_id IS '商户';

COMMENT ON COLUMN payment_events.event_key IS '回调通知号或主动查询唯一标识';

COMMENT ON COLUMN payment_events.event_type IS 'PAY_NOTIFY/QUERY/CLOSE';

COMMENT ON COLUMN payment_events.payload_digest IS '原始内容摘要';

COMMENT ON COLUMN payment_events.payload_asset_id IS '→media_assets；受控加密原始报文引用';

COMMENT ON COLUMN payment_events.status IS 'RECEIVED/PROCESSED/RETRY/REJECTED';

COMMENT ON COLUMN payment_events.error_code IS '异常分类';

COMMENT ON COLUMN payment_events.handled_at IS '处理时间';

CREATE TABLE refunds (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  refund_no varchar(40) NOT NULL,
  order_id bigint NOT NULL,
  payment_id bigint NOT NULL,
  applicant_user_id bigint,
  case_id bigint,
  amount_cent bigint NOT NULL,
  reason_code varchar(48) NOT NULL,
  reason_detail text NOT NULL DEFAULT '',
  evidence_asset_ids jsonb NOT NULL DEFAULT '[]'::jsonb,
  status varchar(24) NOT NULL,
  funds_status varchar(16) NOT NULL,
  reviewer_id bigint,
  approval_id bigint,
  provider_refund_id varchar(128),
  submitted_at timestamptz,
  success_at timestamptz,
  failure_code varchar(64),
  version integer NOT NULL DEFAULT 1
);

COMMENT ON TABLE refunds IS '退款单';

COMMENT ON COLUMN refunds.refund_no IS '业务退款号';

COMMENT ON COLUMN refunds.order_id IS '→orders';

COMMENT ON COLUMN refunds.payment_id IS '→payments';

COMMENT ON COLUMN refunds.applicant_user_id IS '→users；系统发起可空';

COMMENT ON COLUMN refunds.case_id IS '→after_sales_cases';

COMMENT ON COLUMN refunds.amount_cent IS '申请及批准金额，>0；批准后不可改';

COMMENT ON COLUMN refunds.reason_code IS '原因';

COMMENT ON COLUMN refunds.reason_detail IS '默认空';

COMMENT ON COLUMN refunds.evidence_asset_ids IS '默认 []';

COMMENT ON COLUMN refunds.status IS 'APPLIED/REVIEWING/APPROVED/SUBMITTED/PROCESSING/SUCCESS/FAILED/REJECTED/CANCELLED';

COMMENT ON COLUMN refunds.funds_status IS 'NONE/RESERVED/CONSUMED/RELEASED';

COMMENT ON COLUMN refunds.reviewer_id IS '→admin_users';

COMMENT ON COLUMN refunds.approval_id IS '→admin_approvals';

COMMENT ON COLUMN refunds.provider_refund_id IS '渠道退款号';

COMMENT ON COLUMN refunds.submitted_at IS '首次提交渠道时间';

COMMENT ON COLUMN refunds.success_at IS '渠道确认成功';

COMMENT ON COLUMN refunds.failure_code IS '失败原因';

COMMENT ON COLUMN refunds.version IS '默认 1';

