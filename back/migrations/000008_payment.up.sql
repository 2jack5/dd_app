CREATE FUNCTION dd_guard_payment_event() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP='DELETE' THEN
    RAISE EXCEPTION 'payment event facts cannot be deleted' USING ERRCODE='55000';
  END IF;
  IF (to_jsonb(NEW)-ARRAY['payment_id','status','error_code','handled_at','updated_at'])
       IS DISTINCT FROM (to_jsonb(OLD)-ARRAY['payment_id','status','error_code','handled_at','updated_at'])
     OR (OLD.payment_id IS NOT NULL AND NEW.payment_id IS DISTINCT FROM OLD.payment_id) THEN
    RAISE EXCEPTION 'payment event facts are immutable' USING ERRCODE='55000';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER tr_payment_event_facts BEFORE UPDATE OR DELETE ON payment_events
  FOR EACH ROW EXECUTE FUNCTION dd_guard_payment_event();

