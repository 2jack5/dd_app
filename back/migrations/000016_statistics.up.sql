-- 活跃事件与统计
-- 按文件编号升序执行；本文件与对应 down 文件由迁移工具记录版本。
BEGIN;

CREATE TABLE user_activity_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  user_id bigint NOT NULL,
  event_key varchar(128) NOT NULL,
  event_type varchar(32) NOT NULL,
  occurred_at timestamptz NOT NULL,
  received_at timestamptz NOT NULL,
  context jsonb NOT NULL DEFAULT '{}'::jsonb
);

COMMENT ON TABLE user_activity_events IS '用户活跃事件';

COMMENT ON COLUMN user_activity_events.user_id IS '→users';

COMMENT ON COLUMN user_activity_events.event_key IS '客户端事件唯一号';

COMMENT ON COLUMN user_activity_events.event_type IS 'APP_ACTIVE/VIEW_SERVICE/CREATE_ORDER';

COMMENT ON COLUMN user_activity_events.occurred_at IS '事件发生时间';

COMMENT ON COLUMN user_activity_events.received_at IS '服务端接收时间';

COMMENT ON COLUMN user_activity_events.context IS '默认 {}；仅白名单维度';

CREATE TABLE daily_metrics (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  stat_date date NOT NULL,
  metric_code varchar(48) NOT NULL,
  dimension_key varchar(128) NOT NULL,
  value_bigint bigint NOT NULL,
  source_watermark timestamptz NOT NULL,
  calculated_at timestamptz NOT NULL
);

COMMENT ON TABLE daily_metrics IS '日统计投影';

COMMENT ON COLUMN daily_metrics.stat_date IS '业务日期，Asia/Shanghai';

COMMENT ON COLUMN daily_metrics.metric_code IS 'DAU/PAID_GMV/REFUND/COMMISSION/COACH_ACTIVE 等';

COMMENT ON COLUMN daily_metrics.dimension_key IS 'ALL 或规范化游戏维度';

COMMENT ON COLUMN daily_metrics.value_bigint IS '计数或分金额';

COMMENT ON COLUMN daily_metrics.source_watermark IS '源数据水位';

COMMENT ON COLUMN daily_metrics.calculated_at IS '计算时间';

CREATE UNIQUE INDEX uq_user_activity_events_event_key ON user_activity_events (event_key);

CREATE UNIQUE INDEX uq_daily_metrics_stat_date_metric_code_dimension_key ON daily_metrics (stat_date, metric_code, dimension_key);

CREATE INDEX ix_user_activity_events_1 ON user_activity_events (user_id);

ALTER TABLE user_activity_events ADD CONSTRAINT ck_user_activity_events_event_type CHECK (event_type IN ('APP_ACTIVE','VIEW_SERVICE','CREATE_ORDER'));

ALTER TABLE daily_metrics ADD CONSTRAINT ck_daily_metrics_metric_code CHECK (metric_code IN ('DAU','PAID_GMV','REFUND','COMMISSION','COACH_ACTIVE'));

CREATE INDEX ix_user_activity_events_2 ON user_activity_events (occurred_at, user_id);

ALTER TABLE user_activity_events ADD CONSTRAINT ck_json_user_activity_events_context CHECK (jsonb_typeof(context)='object');

CREATE TRIGGER tr_user_activity_events_append_only BEFORE UPDATE OR DELETE ON user_activity_events FOR EACH ROW EXECUTE FUNCTION dd_reject_event_mutation();

COMMIT;
