-- 渠道对账与差异
-- 按文件编号升序执行；本文件与对应 down 文件由迁移工具记录版本。
BEGIN;

CREATE TABLE reconciliation_runs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  provider varchar(32) NOT NULL,
  merchant_id varchar(64) NOT NULL,
  bill_type varchar(24) NOT NULL,
  bill_date date NOT NULL,
  run_no integer NOT NULL,
  status varchar(24) NOT NULL,
  bill_asset_id bigint,
  bill_timezone varchar(64) NOT NULL,
  mismatch_count integer NOT NULL DEFAULT 0,
  started_at timestamptz,
  finished_at timestamptz
);

COMMENT ON TABLE reconciliation_runs IS '对账任务与重跑版本';

COMMENT ON COLUMN reconciliation_runs.provider IS '渠道';

COMMENT ON COLUMN reconciliation_runs.merchant_id IS '商户';

COMMENT ON COLUMN reconciliation_runs.bill_type IS 'PAYMENT/REFUND/SETTLEMENT';

COMMENT ON COLUMN reconciliation_runs.bill_date IS '渠道账单日期，按账单时区';

COMMENT ON COLUMN reconciliation_runs.run_no IS '重跑版本';

COMMENT ON COLUMN reconciliation_runs.status IS 'PENDING/DOWNLOADED/PARSED/COMPLETED/FAILED';

COMMENT ON COLUMN reconciliation_runs.bill_asset_id IS '→media_assets；原账单';

COMMENT ON COLUMN reconciliation_runs.bill_timezone IS '渠道账单时区';

COMMENT ON COLUMN reconciliation_runs.mismatch_count IS '默认 0';

COMMENT ON COLUMN reconciliation_runs.started_at IS '开始';

COMMENT ON COLUMN reconciliation_runs.finished_at IS '结束';

CREATE TABLE reconciliation_lines (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  run_id bigint NOT NULL,
  line_no integer NOT NULL,
  business_no varchar(128),
  provider_ref varchar(128) NOT NULL,
  amount_cent bigint NOT NULL,
  fee_cent bigint NOT NULL DEFAULT 0,
  currency char(3) NOT NULL DEFAULT 'CNY',
  channel_status varchar(32) NOT NULL,
  occurred_at timestamptz NOT NULL,
  row_digest varchar(64) NOT NULL
);

COMMENT ON TABLE reconciliation_lines IS '渠道账单标准行';

COMMENT ON COLUMN reconciliation_lines.run_id IS '→reconciliation_runs';

COMMENT ON COLUMN reconciliation_lines.line_no IS '原文件行号';

COMMENT ON COLUMN reconciliation_lines.business_no IS '商户支付/退款/结算单号';

COMMENT ON COLUMN reconciliation_lines.provider_ref IS '渠道流水';

COMMENT ON COLUMN reconciliation_lines.amount_cent IS '账单金额';

COMMENT ON COLUMN reconciliation_lines.fee_cent IS '默认 0；手续费';

COMMENT ON COLUMN reconciliation_lines.currency IS '默认 CNY';

COMMENT ON COLUMN reconciliation_lines.channel_status IS '原渠道状态';

COMMENT ON COLUMN reconciliation_lines.occurred_at IS '交易时间';

COMMENT ON COLUMN reconciliation_lines.row_digest IS '原行摘要';

CREATE TABLE reconciliation_diffs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  run_id bigint NOT NULL,
  line_id bigint,
  local_type varchar(24) NOT NULL,
  local_id bigint,
  diff_key varchar(160) NOT NULL,
  diff_type varchar(32) NOT NULL,
  local_amount_cent bigint,
  channel_amount_cent bigint,
  status varchar(24) NOT NULL,
  assignee_id bigint,
  resolution text,
  resolved_at timestamptz
);

COMMENT ON TABLE reconciliation_diffs IS '对账差异工单';

COMMENT ON COLUMN reconciliation_diffs.run_id IS '→reconciliation_runs';

COMMENT ON COLUMN reconciliation_diffs.line_id IS '→reconciliation_lines；本地单边时可空';

COMMENT ON COLUMN reconciliation_diffs.local_type IS 'PAYMENT/REFUND/SETTLEMENT';

COMMENT ON COLUMN reconciliation_diffs.local_id IS '本地业务记录 ID，逻辑关联';

COMMENT ON COLUMN reconciliation_diffs.diff_key IS '本次差异稳定键';

COMMENT ON COLUMN reconciliation_diffs.diff_type IS 'LOCAL_ONLY/CHANNEL_ONLY/AMOUNT/STATUS/FEE';

COMMENT ON COLUMN reconciliation_diffs.local_amount_cent IS '本地金额';

COMMENT ON COLUMN reconciliation_diffs.channel_amount_cent IS '渠道金额';

COMMENT ON COLUMN reconciliation_diffs.status IS 'OPEN/INVESTIGATING/RESOLVED/IGNORED';

COMMENT ON COLUMN reconciliation_diffs.assignee_id IS '→admin_users';

COMMENT ON COLUMN reconciliation_diffs.resolution IS '处理依据';

COMMENT ON COLUMN reconciliation_diffs.resolved_at IS '处理时间';

CREATE UNIQUE INDEX uq_reconciliation_runs_provider_merchant_id_bill_typ_092ff21c47 ON reconciliation_runs (provider, merchant_id, bill_type, bill_date, run_no);

CREATE UNIQUE INDEX uq_reconciliation_lines_run_id_line_no ON reconciliation_lines (run_id, line_no);

CREATE UNIQUE INDEX uq_reconciliation_diffs_run_id_diff_key ON reconciliation_diffs (run_id, diff_key);

CREATE INDEX ix_reconciliation_runs_1 ON reconciliation_runs (bill_asset_id);

CREATE INDEX ix_reconciliation_lines_1 ON reconciliation_lines (run_id);

CREATE INDEX ix_reconciliation_diffs_1 ON reconciliation_diffs (run_id);

CREATE INDEX ix_reconciliation_diffs_2 ON reconciliation_diffs (line_id);

CREATE INDEX ix_reconciliation_diffs_3 ON reconciliation_diffs (assignee_id);

ALTER TABLE reconciliation_runs ADD CONSTRAINT ck_reconciliation_runs_bill_type CHECK (bill_type IN ('PAYMENT','REFUND','SETTLEMENT'));

ALTER TABLE reconciliation_runs ADD CONSTRAINT ck_reconciliation_runs_run_no_positive CHECK (run_no>0);

ALTER TABLE reconciliation_runs ADD CONSTRAINT ck_reconciliation_runs_status CHECK (status IN ('PENDING','DOWNLOADED','PARSED','COMPLETED','FAILED'));

ALTER TABLE reconciliation_diffs ADD CONSTRAINT ck_reconciliation_diffs_local_type CHECK (local_type IN ('PAYMENT','REFUND','SETTLEMENT','SETTLEMENT_SUPPLEMENT'));

ALTER TABLE reconciliation_diffs ADD CONSTRAINT ck_reconciliation_diffs_diff_type CHECK (diff_type IN ('LOCAL_ONLY','CHANNEL_ONLY','AMOUNT','STATUS','FEE'));

ALTER TABLE reconciliation_diffs ADD CONSTRAINT ck_reconciliation_diffs_status CHECK (status IN ('OPEN','INVESTIGATING','RESOLVED','IGNORED'));

ALTER TABLE reconciliation_runs ADD CONSTRAINT ck_reconcile_mismatch CHECK (mismatch_count>=0);

ALTER TABLE reconciliation_lines ADD CONSTRAINT ck_bill_line CHECK (line_no>0 AND fee_cent>=0);

CREATE INDEX ix_reconciliation_runs_2 ON reconciliation_runs (bill_date, status);

CREATE INDEX ix_reconciliation_lines_2 ON reconciliation_lines (run_id, provider_ref);

CREATE INDEX ix_reconciliation_lines_3 ON reconciliation_lines (business_no);

CREATE INDEX ix_reconciliation_diffs_4 ON reconciliation_diffs (run_id, status);

CREATE INDEX ix_reconciliation_diffs_5 ON reconciliation_diffs (status, created_at);

COMMIT;
