-- 首页运营、内容审核与处罚
-- 按文件编号升序执行；本文件与对应 down 文件由迁移工具记录版本。
BEGIN;

CREATE TABLE activities (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  title varchar(128) NOT NULL,
  content jsonb NOT NULL,
  cover_asset_id bigint,
  starts_at timestamptz NOT NULL,
  ends_at timestamptz NOT NULL,
  status varchar(16) NOT NULL,
  created_by bigint NOT NULL,
  content_version integer NOT NULL DEFAULT 1,
  version integer NOT NULL DEFAULT 1
);

COMMENT ON TABLE activities IS '展示活动';

COMMENT ON COLUMN activities.title IS '标题';

COMMENT ON COLUMN activities.content IS '结构化展示内容';

COMMENT ON COLUMN activities.cover_asset_id IS '→media_assets';

COMMENT ON COLUMN activities.starts_at IS '开始';

COMMENT ON COLUMN activities.ends_at IS '结束';

COMMENT ON COLUMN activities.status IS 'DRAFT/PUBLISHED/OFFLINE';

COMMENT ON COLUMN activities.created_by IS '→admin_users';

COMMENT ON COLUMN activities.content_version IS '默认 1；内容审核版本，提交新版本时递增；独立于登录或价格版本';

COMMENT ON COLUMN activities.version IS '默认 1；更新时通过 WHERE version 校验并显式递增';

CREATE TABLE banners (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  placement varchar(48) NOT NULL,
  title varchar(128) NOT NULL,
  image_asset_id bigint NOT NULL,
  target_type varchar(24) NOT NULL,
  target_id bigint NOT NULL,
  starts_at timestamptz NOT NULL,
  ends_at timestamptz NOT NULL,
  status varchar(16) NOT NULL,
  sort_order integer NOT NULL DEFAULT 0
);

COMMENT ON TABLE banners IS '首页 Banner 与运营位';

COMMENT ON COLUMN banners.placement IS '首页位置编码';

COMMENT ON COLUMN banners.title IS '标题';

COMMENT ON COLUMN banners.image_asset_id IS '→media_assets';

COMMENT ON COLUMN banners.target_type IS 'GAME/COACH/SERVICE/ACTIVITY';

COMMENT ON COLUMN banners.target_id IS '对应目标，逻辑关联';

COMMENT ON COLUMN banners.starts_at IS '开始';

COMMENT ON COLUMN banners.ends_at IS '结束';

COMMENT ON COLUMN banners.status IS 'DRAFT/PUBLISHED/OFFLINE';

COMMENT ON COLUMN banners.sort_order IS '默认 0';

CREATE TABLE coach_recommendations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  placement varchar(48) NOT NULL,
  coach_id bigint NOT NULL,
  game_id bigint,
  starts_at timestamptz NOT NULL,
  ends_at timestamptz NOT NULL,
  status varchar(16) NOT NULL,
  sort_order integer NOT NULL DEFAULT 0
);

COMMENT ON TABLE coach_recommendations IS '首页推荐陪练';

COMMENT ON COLUMN coach_recommendations.placement IS '推荐位';

COMMENT ON COLUMN coach_recommendations.coach_id IS '→coaches';

COMMENT ON COLUMN coach_recommendations.game_id IS '→games；空表示全站';

COMMENT ON COLUMN coach_recommendations.starts_at IS '开始';

COMMENT ON COLUMN coach_recommendations.ends_at IS '结束';

COMMENT ON COLUMN coach_recommendations.status IS 'ENABLED/DISABLED';

COMMENT ON COLUMN coach_recommendations.sort_order IS '默认 0';

CREATE TABLE content_audits (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  subject_type varchar(32) NOT NULL,
  subject_id bigint NOT NULL,
  revision integer NOT NULL,
  submitted_by_user_id bigint,
  submitted_by_admin_id bigint,
  content_snapshot jsonb NOT NULL,
  source_version integer NOT NULL,
  provider_task_ref varchar(128),
  status varchar(24) NOT NULL,
  risk_codes jsonb NOT NULL DEFAULT '[]'::jsonb,
  reviewer_id bigint,
  reason text,
  decided_at timestamptz
);

COMMENT ON TABLE content_audits IS '内容审核任务与提交版本';

COMMENT ON COLUMN content_audits.subject_type IS 'USER/COACH/SERVICE/SKILL/REVIEW_CONTENT/ASSET/ACTIVITY';

COMMENT ON COLUMN content_audits.subject_id IS '业务对象 ID，逻辑关联';

COMMENT ON COLUMN content_audits.revision IS '该对象提交版本';

COMMENT ON COLUMN content_audits.submitted_by_user_id IS '→users';

COMMENT ON COLUMN content_audits.submitted_by_admin_id IS '→admin_users';

COMMENT ON COLUMN content_audits.content_snapshot IS '本次待审文本及资源引用';

COMMENT ON COLUMN content_audits.source_version IS '提交时业务版本，防止旧审核覆盖新内容';

COMMENT ON COLUMN content_audits.provider_task_ref IS '自动审核任务引用';

COMMENT ON COLUMN content_audits.status IS 'PENDING/AUTO_PASSED/MANUAL_REVIEW/APPROVED/REJECTED/SUPERSEDED';

COMMENT ON COLUMN content_audits.risk_codes IS '默认 []';

COMMENT ON COLUMN content_audits.reviewer_id IS '→admin_users';

COMMENT ON COLUMN content_audits.reason IS '审核依据';

COMMENT ON COLUMN content_audits.decided_at IS '决策时间';

CREATE TABLE user_penalties (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  user_id bigint NOT NULL,
  coach_id bigint,
  service_id bigint,
  case_id bigint,
  action varchar(24) NOT NULL,
  reason text NOT NULL,
  starts_at timestamptz NOT NULL,
  ends_at timestamptz,
  status varchar(16) NOT NULL,
  admin_id bigint NOT NULL,
  revoked_at timestamptz
);

COMMENT ON TABLE user_penalties IS '违规处罚与恢复';

COMMENT ON COLUMN user_penalties.user_id IS '→users';

COMMENT ON COLUMN user_penalties.coach_id IS '→coaches';

COMMENT ON COLUMN user_penalties.service_id IS '→coach_services';

COMMENT ON COLUMN user_penalties.case_id IS '→after_sales_cases';

COMMENT ON COLUMN user_penalties.action IS 'BAN_USER/SUSPEND_COACH/BLOCK_SERVICE';

COMMENT ON COLUMN user_penalties.reason IS '处罚依据';

COMMENT ON COLUMN user_penalties.starts_at IS '生效';

COMMENT ON COLUMN user_penalties.ends_at IS '到期；空为长期';

COMMENT ON COLUMN user_penalties.status IS 'ACTIVE/REVOKED/EXPIRED';

COMMENT ON COLUMN user_penalties.admin_id IS '→admin_users';

COMMENT ON COLUMN user_penalties.revoked_at IS '撤销时间';

CREATE UNIQUE INDEX uq_content_audits_subject_type_subject_id_revision ON content_audits (subject_type, subject_id, revision);

CREATE INDEX ix_activities_1 ON activities (cover_asset_id);

CREATE INDEX ix_activities_2 ON activities (created_by);

CREATE INDEX ix_banners_1 ON banners (image_asset_id);

CREATE INDEX ix_coach_recommendations_1 ON coach_recommendations (coach_id);

CREATE INDEX ix_coach_recommendations_2 ON coach_recommendations (game_id);

CREATE INDEX ix_content_audits_1 ON content_audits (submitted_by_user_id);

CREATE INDEX ix_content_audits_2 ON content_audits (submitted_by_admin_id);

CREATE INDEX ix_content_audits_3 ON content_audits (reviewer_id);

CREATE INDEX ix_user_penalties_1 ON user_penalties (user_id);

CREATE INDEX ix_user_penalties_2 ON user_penalties (coach_id);

CREATE INDEX ix_user_penalties_3 ON user_penalties (service_id);

