-- 业务规则、幂等与可靠任务
-- 按文件编号升序执行；本文件与对应 down 文件由迁移工具记录版本。
BEGIN;

CREATE TABLE business_rule_versions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  code varchar(48) NOT NULL,
  revision integer NOT NULL,
  config jsonb NOT NULL,
  status varchar(16) NOT NULL,
  effective_at timestamptz NOT NULL,
  expires_at timestamptz,
  created_by bigint NOT NULL,
  approval_id bigint,
  version integer NOT NULL DEFAULT 1
);

COMMENT ON TABLE business_rule_versions IS '业务规则版本';

COMMENT ON COLUMN business_rule_versions.code IS 'ORDER/CANCELLATION/SETTLEMENT/SUPPORT 等';

COMMENT ON COLUMN business_rule_versions.revision IS '版本';

COMMENT ON COLUMN business_rule_versions.config IS '具备校验 schema 的规则';

COMMENT ON COLUMN business_rule_versions.status IS 'DRAFT/PUBLISHED/RETIRED';

COMMENT ON COLUMN business_rule_versions.effective_at IS '生效';

COMMENT ON COLUMN business_rule_versions.expires_at IS '结束';

COMMENT ON COLUMN business_rule_versions.created_by IS '→admin_users';

COMMENT ON COLUMN business_rule_versions.approval_id IS '→admin_approvals';

COMMENT ON COLUMN business_rule_versions.version IS '默认 1；更新时通过 WHERE version 校验并显式递增';

CREATE TABLE idempotency_keys (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  actor_type varchar(16) NOT NULL,
  actor_id bigint NOT NULL,
  operation varchar(64) NOT NULL,
  biz_key varchar(128) NOT NULL,
  request_hash varchar(64) NOT NULL,
  status varchar(16) NOT NULL,
  resource_type varchar(32),
  resource_id bigint,
  response_summary jsonb NOT NULL DEFAULT '{}'::jsonb,
  expires_at timestamptz NOT NULL
);

COMMENT ON TABLE idempotency_keys IS '请求幂等';

COMMENT ON COLUMN idempotency_keys.actor_type IS 'USER/ADMIN/SYSTEM';

COMMENT ON COLUMN idempotency_keys.actor_id IS '主体 ID；系统使用固定主体';

COMMENT ON COLUMN idempotency_keys.operation IS '接口操作';

COMMENT ON COLUMN idempotency_keys.biz_key IS '客户端幂等键';

COMMENT ON COLUMN idempotency_keys.request_hash IS '规范化请求摘要';

COMMENT ON COLUMN idempotency_keys.status IS 'PROCESSING/SUCCEEDED/FAILED';

COMMENT ON COLUMN idempotency_keys.resource_type IS '结果资源';

COMMENT ON COLUMN idempotency_keys.resource_id IS '结果 ID';

COMMENT ON COLUMN idempotency_keys.response_summary IS '默认 {}；脱敏可重放结果';

COMMENT ON COLUMN idempotency_keys.expires_at IS '过期清理时间';

CREATE TABLE outbox_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  event_key varchar(160) NOT NULL,
  aggregate_type varchar(32) NOT NULL,
  aggregate_id bigint NOT NULL,
  event_type varchar(64) NOT NULL,
  payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  status varchar(16) NOT NULL,
  available_at timestamptz NOT NULL,
  locked_until timestamptz,
  lock_token varchar(64),
  attempts integer NOT NULL DEFAULT 0,
  last_error text
);

COMMENT ON TABLE outbox_events IS '事务消息与后台任务';

COMMENT ON COLUMN outbox_events.event_key IS '稳定业务事件键';

COMMENT ON COLUMN outbox_events.aggregate_type IS '交易、审核、售后、通知、对账及配置业务聚合类型';

COMMENT ON COLUMN outbox_events.aggregate_id IS '聚合 ID，逻辑关联';

COMMENT ON COLUMN outbox_events.event_type IS '消息类型';

COMMENT ON COLUMN outbox_events.payload IS '默认 {}；不存密钥及明文隐私';

COMMENT ON COLUMN outbox_events.status IS 'PENDING/PROCESSING/DONE/DEAD';

COMMENT ON COLUMN outbox_events.available_at IS '下次可执行时间';

COMMENT ON COLUMN outbox_events.locked_until IS '任务租约截止';

COMMENT ON COLUMN outbox_events.lock_token IS '本轮认领标识';

COMMENT ON COLUMN outbox_events.attempts IS '默认 0';

COMMENT ON COLUMN outbox_events.last_error IS '脱敏错误';

CREATE UNIQUE INDEX uq_business_rule_versions_code_revision ON business_rule_versions (code, revision);

CREATE UNIQUE INDEX uq_idempotency_keys_actor_type_actor_id_operation_biz_key ON idempotency_keys (actor_type, actor_id, operation, biz_key);

CREATE UNIQUE INDEX uq_outbox_events_event_key ON outbox_events (event_key);

CREATE INDEX ix_business_rule_versions_1 ON business_rule_versions (created_by);

CREATE INDEX ix_business_rule_versions_2 ON business_rule_versions (approval_id);

ALTER TABLE business_rule_versions ADD CONSTRAINT ck_business_rule_versions_code CHECK (code IN ('ORDER','CANCELLATION','SETTLEMENT','SUPPORT'));

ALTER TABLE business_rule_versions ADD CONSTRAINT ck_business_rule_versions_revision_positive CHECK (revision>0);

ALTER TABLE business_rule_versions ADD CONSTRAINT ck_business_rule_versions_status CHECK (status IN ('DRAFT','PUBLISHED','RETIRED'));

ALTER TABLE business_rule_versions ADD CONSTRAINT ck_business_rule_versions_version_positive CHECK (version>0);

ALTER TABLE idempotency_keys ADD CONSTRAINT ck_idempotency_keys_actor_type CHECK (actor_type IN ('USER','ADMIN','SYSTEM'));

ALTER TABLE idempotency_keys ADD CONSTRAINT ck_idempotency_keys_status CHECK (status IN ('PROCESSING','SUCCEEDED','FAILED'));

ALTER TABLE outbox_events ADD CONSTRAINT ck_outbox_events_aggregate_type CHECK (aggregate_type IN ('ORDER','PAYMENT','REFUND','SETTLEMENT','SETTLEMENT_SUPPLEMENT','COACH_APPLICATION','IDENTITY_CHECK','COACH_SKILL','AFTER_SALES_CASE','CONTENT_AUDIT','NOTIFICATION','RECONCILIATION','USER','COACH','SERVICE','BUSINESS_RULE'));

ALTER TABLE outbox_events ADD CONSTRAINT ck_outbox_events_status CHECK (status IN ('PENDING','PROCESSING','DONE','DEAD'));

ALTER TABLE business_rule_versions ADD CONSTRAINT ck_business_rule_time CHECK (expires_at IS NULL OR effective_at<expires_at);

ALTER TABLE outbox_events ADD CONSTRAINT ck_outbox_attempts CHECK (attempts>=0);

ALTER TABLE business_rule_versions ADD CONSTRAINT ex_business_rule_versions EXCLUDE USING gist (code WITH =, tstzrange(effective_at,expires_at,'[)') WITH &&) WHERE (status='PUBLISHED');

CREATE INDEX ix_business_rule_versions_3 ON business_rule_versions (code, status, effective_at);

CREATE INDEX ix_idempotency_keys_1 ON idempotency_keys (expires_at);

CREATE INDEX ix_outbox_events_1 ON outbox_events (status, available_at, id);

CREATE INDEX ix_outbox_events_2 ON outbox_events (status, locked_until);

ALTER TABLE business_rule_versions ADD CONSTRAINT ck_json_business_rule_versions_config CHECK (jsonb_typeof(config)='object');

ALTER TABLE idempotency_keys ADD CONSTRAINT ck_json_idempotency_keys_response_summary CHECK (jsonb_typeof(response_summary)='object');

ALTER TABLE outbox_events ADD CONSTRAINT ck_json_outbox_events_payload CHECK (jsonb_typeof(payload)='object');

COMMIT;
