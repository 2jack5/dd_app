CREATE FUNCTION dd_guard_settlement_adjustment() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP='DELETE' THEN
    RAISE EXCEPTION 'settlement adjustments cannot be deleted' USING ERRCODE='55000';
  END IF;
  IF (to_jsonb(NEW)-ARRAY['recovery_status','recovered_cent','provider_ref','updated_at'])
       IS DISTINCT FROM (to_jsonb(OLD)-ARRAY['recovery_status','recovered_cent','provider_ref','updated_at']) THEN
    RAISE EXCEPTION 'settlement adjustment amounts are immutable' USING ERRCODE='55000';
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER tr_adjustment_facts BEFORE UPDATE OR DELETE ON settlement_adjustments
  FOR EACH ROW EXECUTE FUNCTION dd_guard_settlement_adjustment();

