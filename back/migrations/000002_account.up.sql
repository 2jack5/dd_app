-- 用户、登录身份与协议
-- 按文件编号升序执行；本文件与对应 down 文件由迁移工具记录版本。
BEGIN;

CREATE TABLE users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  user_no varchar(32) NOT NULL,
  nickname varchar(64) NOT NULL,
  avatar_asset_id bigint,
  phone_cipher bytea,
  phone_digest varchar(64),
  status varchar(24) NOT NULL DEFAULT 'ACTIVE',
  auth_version integer NOT NULL DEFAULT 1,
  last_login_at timestamptz,
  cancelled_at timestamptz,
  content_version integer NOT NULL DEFAULT 1
);

COMMENT ON TABLE users IS '用户';

COMMENT ON COLUMN users.user_no IS '唯一公开编号';

COMMENT ON COLUMN users.nickname IS '已审核昵称';

COMMENT ON COLUMN users.avatar_asset_id IS '→media_assets';

COMMENT ON COLUMN users.phone_cipher IS '手机号密文';

COMMENT ON COLUMN users.phone_digest IS '规范化手机号的密钥摘要，供精确查找';

COMMENT ON COLUMN users.status IS '默认 ACTIVE；ACTIVE/BANNED/CANCEL_PENDING/CANCELLED';

COMMENT ON COLUMN users.auth_version IS '默认 1；注销、封禁时递增使旧 token 失效';

COMMENT ON COLUMN users.last_login_at IS '最近登录';

COMMENT ON COLUMN users.cancelled_at IS '注销完成时间';

COMMENT ON COLUMN users.content_version IS '默认 1；内容审核版本，提交新版本时递增；独立于登录或价格版本';

CREATE TABLE auth_identities (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  user_id bigint NOT NULL,
  provider varchar(24) NOT NULL,
  app_id varchar(64) NOT NULL,
  subject varchar(128) NOT NULL,
  union_id varchar(128),
  bound_at timestamptz NOT NULL
);

COMMENT ON TABLE auth_identities IS '第三方登录身份';

COMMENT ON COLUMN auth_identities.user_id IS '→users';

COMMENT ON COLUMN auth_identities.provider IS 'WECHAT_MINI/WECHAT_APP';

COMMENT ON COLUMN auth_identities.app_id IS '微信应用标识';

COMMENT ON COLUMN auth_identities.subject IS '该应用下 OpenID';

COMMENT ON COLUMN auth_identities.union_id IS '开放平台关联标识；不作为实名认证凭据';

COMMENT ON COLUMN auth_identities.bound_at IS '绑定时间';

CREATE TABLE agreement_acceptances (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  user_id bigint NOT NULL,
  agreement_code varchar(48) NOT NULL,
  agreement_version varchar(32) NOT NULL,
  content_hash varchar(64) NOT NULL,
  content_asset_id bigint NOT NULL,
  order_id bigint,
  accepted_at timestamptz NOT NULL,
  request_id varchar(64) NOT NULL
);

COMMENT ON TABLE agreement_acceptances IS '协议同意记录';

COMMENT ON COLUMN agreement_acceptances.user_id IS '→users';

COMMENT ON COLUMN agreement_acceptances.agreement_code IS 'USER/PRIVACY/COACH/ORDER';

COMMENT ON COLUMN agreement_acceptances.agreement_version IS '版本';

COMMENT ON COLUMN agreement_acceptances.content_hash IS '协议正文摘要';

COMMENT ON COLUMN agreement_acceptances.content_asset_id IS '→media_assets；不可变协议文本';

COMMENT ON COLUMN agreement_acceptances.order_id IS '→orders；下单协议可关联订单';

COMMENT ON COLUMN agreement_acceptances.accepted_at IS '同意时间';

COMMENT ON COLUMN agreement_acceptances.request_id IS '请求追踪号';

CREATE UNIQUE INDEX uq_users_user_no ON users (user_no);

CREATE UNIQUE INDEX uq_auth_identities_provider_app_id_subject ON auth_identities (provider, app_id, subject);

CREATE UNIQUE INDEX uq_agreement_acceptances_user_id_agreement_code_agre_cb1ccb0772 ON agreement_acceptances (user_id, agreement_code, agreement_version, request_id);

CREATE INDEX ix_users_1 ON users (avatar_asset_id);

CREATE INDEX ix_auth_identities_1 ON auth_identities (user_id);

CREATE INDEX ix_agreement_acceptances_1 ON agreement_acceptances (user_id);

CREATE INDEX ix_agreement_acceptances_2 ON agreement_acceptances (content_asset_id);

CREATE INDEX ix_agreement_acceptances_3 ON agreement_acceptances (order_id);

ALTER TABLE users ADD CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE','BANNED','CANCEL_PENDING','CANCELLED'));

ALTER TABLE users ADD CONSTRAINT ck_users_auth_version_positive CHECK (auth_version>0);

ALTER TABLE users ADD CONSTRAINT ck_users_content_version_positive CHECK (content_version>0);

ALTER TABLE auth_identities ADD CONSTRAINT ck_auth_identities_provider CHECK (provider IN ('WECHAT_MINI','WECHAT_APP'));

ALTER TABLE agreement_acceptances ADD CONSTRAINT ck_agreement_acceptances_agreement_code CHECK (agreement_code IN ('USER','PRIVACY','COACH','ORDER'));

CREATE INDEX ix_users_2 ON users (phone_digest);

CREATE INDEX ix_auth_identities_2 ON auth_identities (union_id);

CREATE INDEX ix_agreement_acceptances_4 ON agreement_acceptances (user_id, agreement_code, accepted_at);

COMMIT;
