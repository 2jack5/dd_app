-- 金额、归属、批准与请求号是指令事实；只允许推进处理进度。
CREATE FUNCTION dd_guard_settlement_supplement() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='DELETE' THEN
  RAISE EXCEPTION 'settlement supplements cannot be deleted' USING ERRCODE='55000';
 END IF;
 IF (to_jsonb(NEW)-ARRAY['status','provider_ref','submitted_at','succeeded_at','failure_code','version','updated_at'])
    IS DISTINCT FROM (to_jsonb(OLD)-ARRAY['status','provider_ref','submitted_at','succeeded_at','failure_code','version','updated_at']) THEN
  RAISE EXCEPTION 'settlement supplement instruction is immutable' USING ERRCODE='55000';
 END IF;
 IF OLD.status IN ('SUCCESS','CANCELLED') AND NEW IS DISTINCT FROM OLD THEN
  RAISE EXCEPTION 'settlement supplement is terminal' USING ERRCODE='55000';
 END IF;
 IF OLD.provider_ref IS NOT NULL AND NEW.provider_ref IS DISTINCT FROM OLD.provider_ref THEN
  RAISE EXCEPTION 'settlement supplement channel reference is immutable' USING ERRCODE='55000';
 END IF;
 RETURN NEW;
END;
$$;
CREATE TRIGGER tr_settlement_supplement_facts BEFORE UPDATE OR DELETE ON settlement_supplements
 FOR EACH ROW EXECUTE FUNCTION dd_guard_settlement_supplement();

COMMIT;
